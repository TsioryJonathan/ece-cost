CREATE TABLE resource (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255)  NOT NULL UNIQUE,
    type       VARCHAR(255)  NOT NULL CHECK (type IN ('MATERIAL', 'LABOUR', 'EQUIPMENT')),
    unit       VARCHAR(255)  NOT NULL,
    unit_price NUMERIC(14,2) NOT NULL CHECK (unit_price > 0)
);

CREATE TABLE work_item (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    unit VARCHAR(255) NOT NULL
);

CREATE TABLE work_item_resource (
    work_item_id BIGINT        NOT NULL REFERENCES work_item (id) ON DELETE CASCADE,
    resource_id  BIGINT        NOT NULL REFERENCES resource (id),
    quantity     NUMERIC(12,3) NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (work_item_id, resource_id)
);
